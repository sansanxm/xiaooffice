export function translateRibbonItem(val, key) {
  if (RIBBON_BASE[val]) return RIBBON_BASE[val];

  // Specific key matches
  if (key === 'ribbonAiCreditNote') return 'Sử dụng AI và tiêu tốn tín dụng';
  if (key === 'ribbonReplacePicture') return 'Thay thế hình ảnh';
  if (key === 'ribbonResetSize') return 'Đặt lại kích thước';
  if (key === 'ribbonGroupAdjust') return 'Điều chỉnh';
  if (key === 'ribbonAdd') return 'Thêm';
  if (key === 'ribbonCutoutTolerance') return 'Độ dung sai';
  if (key === 'ribbonPasteSpecialAs') return 'Dưới dạng:';
  if (key === 'ribbonHighlightColors') return 'Màu đánh dấu';

  // Common pattern translations
  if (val.startsWith('Shape (')) {
    return val.replace('Shape (', 'Hình dạng (');
  }
  if (val.startsWith('Picture (')) {
    return val.replace('Picture (', 'Hình ảnh (');
  }
  if (val.startsWith('Theme color ')) {
    return val.replace('Theme color ', 'Màu chủ đề ');
  }
  if (val.startsWith('Heading ')) {
    return val.replace('Heading ', 'Tiêu đề ');
  }
  if (val.startsWith('Apply table style ')) {
    return val.replace('Apply table style ', 'Áp dụng kiểu bảng ');
  }
  if (val.startsWith('Insert the "') && val.endsWith('" cover page')) {
    return val.replace('Insert the "', 'Chèn trang bìa "').replace('" cover page', '"');
  }
  if (val.startsWith('Applies to section ')) {
    return val.replace('Applies to section ', 'Áp dụng cho phần ');
  }
  if (val.startsWith('Paper size must be between ')) {
    return val.replace('Paper size must be between ', 'Kích thước khổ giấy phải nằm trong khoảng ');
  }
  if (val.startsWith('Text shown after ')) {
    return val.replace('Text shown after ', 'Văn bản hiển thị sau ').replace(' (optional)', ' (tùy chọn)');
  }
  if (val.startsWith('Show comments (')) {
    return val.replace('Show comments (', 'Hiển thị nhận xét (');
  }
  if (val.startsWith('Accept changes (')) {
    return val.replace('Accept changes (', 'Chấp nhận thay đổi (').replace(' total)', ' tổng cộng)');
  }
  if (val.startsWith('Reject changes (')) {
    return val.replace('Reject changes (', 'Từ chối thay đổi (').replace(' total)', ' tổng cộng)');
  }

  return null;
}

